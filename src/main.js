console.log(`Finding out if there is Ali on the Hash Map: ${test.has("Ali")}`)
console.log(`Getting all Keys of Hash Map:`)
console.log(test.keys())
console.log(`Getting all Values of Hash Map:`)
console.log(test.values())
console.log(`Length of Hash Map: ${test.length()}`)
console.log(`Getting DNE's value if he exists in Hash Map: ${test.get("DNE")}`)
console.log(`Finding out if there is DNE on the Hash Map: ${test.has("DNE")}`)
